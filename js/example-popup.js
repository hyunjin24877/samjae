  let previousFocus = null;

  // =========================
  // 집 클릭
  // =========================

  document.querySelectorAll(".example-home").forEach((home) => {
    home.addEventListener("click", () => {
      const label = home.querySelector(
        ".example-home-label, .example-home-label-2, .example-home-label-3",
      );

      const location = (
        home.dataset.location ||
        label?.textContent ||
        "지역 사례"
      )
        .trim()
        .replace(/\s+/g, " ");

      // 제목
      title.textContent = location;

      // 설명
      text.textContent =
        home.dataset.description ||
        descriptions[location] ||
        "이 지역의 사례 설명은 준비 중입니다.";

      // =========================
      // 팝업 배경 이미지
      // =========================

      let popupBg = "/img/example/popup-1.svg";

      // 부산
      if (location.includes("부산")) {
        popupBg = "/img/example/popup-2.svg";
      }

      // 고대리 안섬
      else if (location.includes("고대리 안섬")) {
        popupBg = "/img/example/popup-3.svg";
      }

      // 별도 SVG가 없는 지역은 기본 외곽을 사용한다.
      panel.style.setProperty("--popup-frame", `url("${popupBg}")`);

      // 팝업 열기
      if (!popup.open) {
        previousFocus = home;
        popup.showModal();
        // Modal dialogs sit above every normal z-index; keep the cursor
        // in the dialog's top layer while it is open.
        const cursor = document.querySelector(".site-cursor");
        if (cursor) popup.append(cursor);
      }
    });
  });

  // =========================
  // 닫기 버튼
  // =========================

  closeButton.addEventListener("click", () => {
    popup.close();
  });

  // =========================
  // 팝업 바깥 클릭 → 닫기
  // =========================

  popup.addEventListener("click", (event) => {
    if (event.target !== popup) return;

    const rect = panel.getBoundingClientRect();

    const outside =
      event.clientX < rect.left ||
      event.clientX > rect.right ||
      event.clientY < rect.top ||
      event.clientY > rect.bottom;

    if (outside) {
      popup.close();
    }
  });

  // =========================
  // 닫은 뒤 원래 집으로 포커스
  // =========================

  popup.addEventListener("close", () => {
    const cursor = popup.querySelector(".site-cursor");
    if (cursor) document.documentElement.append(cursor);
    previousFocus?.focus({
      preventScroll: true,
    });
  });
